"""Generate the panel's anti-aliased fonts (TFT_eSPI "VLW" smooth fonts).

Renders Nunito (SIL OFL, tools/fonts/) with Pillow into VLW byte arrays and
writes them as C arrays to src/ui/font_data.h, loaded with tft.loadFont().
Character set: printable ASCII + Latin-1 (accents, ñ, ¿, ¡, °, ·).

Run from firmware/:  python tools/make_fonts.py
"""
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
TTF = HERE / "fonts" / "Nunito.ttf"
OUT = HERE.parent / "src" / "ui" / "font_data.h"

LATIN = [c for c in range(0x21, 0x7F)] + [c for c in range(0xA1, 0x100) if c != 0xAD]
DIGITS = [ord(c) for c in "0123456789:-"]

# name, pixel size, weight, characters
FONTS = [
    ("FONT_SMALL", 15, b"Bold", LATIN),     # header, meta lines, times
    ("FONT_BODY", 19, b"Bold", LATIN),      # task text, artist, labels
    ("FONT_TITLE", 25, b"ExtraBold", LATIN),  # song title, strip values
    ("FONT_CLOCK", 46, b"ExtraBold", DIGITS),  # big clock on Habitacion
]


def build_vlw(size: int, weight: bytes, chars: list[int]) -> bytes:
    font = ImageFont.truetype(str(TTF), size)
    font.set_variation_by_name(weight)
    space = font.getlength(" ")

    glyphs = []
    for cp in sorted(chars):
        ch = chr(cp)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        bitmap = b""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            bitmap = img.tobytes()
        glyphs.append((cp, h, w, round(font.getlength(ch)), -t, l, bitmap))

    # TFT_eSPI starts maxAscent/maxDescent from these two header fields (and
    # only grows them from the glyphs), and guesses the space width as
    # (ascent + descent) * 2 / 7. So: header ascent = tallest glyph (else text
    # is pushed down), descent chosen so the space guess matches the font.
    hdr_ascent = max(g[4] for g in glyphs)
    hdr_descent = max(0, round(space * 7 / 2) - hdr_ascent) if 0x41 in chars else 0  # digit-only: no spaces
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, hdr_ascent, hdr_descent))
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for *_, bitmap in glyphs:
        out += bitmap
    return bytes(out)


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    body = ",\n  ".join(rows)
    return f"// {len(data)} bytes\nconst uint8_t {name}[] PROGMEM = {{\n  {body}\n}};\n"


def main() -> None:
    parts = ["// firmware/src/ui/font_data.h -- GENERATED by tools/make_fonts.py, do not edit.\n"
             "// Nunito, SIL Open Font License 1.1 (tools/fonts/OFL.txt).\n"
             "#pragma once\n#include <pgmspace.h>\n#include <stdint.h>\n"]
    total = 0
    for name, size, weight, chars in FONTS:
        data = build_vlw(size, weight, chars)
        total += len(data)
        parts.append(c_array(name, data))
        print(f"{name}: {size}px {weight.decode()} {len(chars)} glyphs, {len(data)} bytes")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({total} bytes of font data)")


if __name__ == "__main__":
    main()
